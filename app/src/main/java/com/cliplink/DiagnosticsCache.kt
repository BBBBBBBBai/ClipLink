package com.cliplink

/**
 * 诊断结果的进程级缓存。
 *
 * ## 为什么需要
 * 切换深色模式、旋转屏幕、改变字体大小等配置变化都会**重建 Activity**。
 * 若诊断信息每次都重新查询，用户每次都会看到一次「正在检测…」的闪烁，
 * 而结果其实和上次完全一样。
 *
 * 放在进程级（object 单例）而非 Activity 里：Activity 重建后实例已换，
 * 只有进程级存储能跨重建保留。进程被杀时缓存自然失效，重新查询即可。
 *
 * 结果本身是幂等的只读查询（监听是否注册、剪切板是否可读），
 * 不会因为复用旧值而产生误导——真正的刷新仍在每次 `onResume` 后台进行。
 */
object DiagnosticsCache {

    /** 上一次查询结果；null 表示尚未查询过。 */
    @Volatile
    var text: String? = null

    /** 状态变化（如服务停止）时清空，避免展示过期信息。 */
    fun clear() {
        text = null
    }
}
